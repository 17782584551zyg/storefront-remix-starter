function getTranslation(key: string): string {
  const keys = key.split('.');
  let result: any = translations;
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      return key;
    }
  }
  return typeof result === 'string' ? result : key;
}

export function useTranslation() {
  return {
    t: getTranslation,
    i18n: {
      changeLanguage: () => {},
      language: 'en',
    },
  };
}
